import { installSimulatedHardware } from './support/tour.mjs';
import { test, expect } from '@playwright/test';

for (const width of [1440, 320]) {
  test(`MLX settings and four-channel recording at ${width}px`, async ({ page, context }, testInfo) => {
    await installSimulatedHardware(context,'mlx90393');
    await page.setViewportSize({ width, height: width === 320 ? 740 : 1000 });
    await page.emulateMedia({ reducedMotion: 'reduce' });
    await page.goto('/sensors/mlx90393/?view=prepare');
    await page.locator('[data-guide-action="confirm"]').click();
    await expect(page.locator('.guide-wiring')).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath('wiring.png'), fullPage: true });
    for (let i = 0; i < 4; i++) await page.locator('[data-guide-action="confirm"]').click();
    await page.locator('[data-guide-action="program-confirm"]').click();
    await page.locator('[data-guide-action="connect"]').click();
    const prepare = page.locator('#guide-host');
    await expect(prepare.locator('[data-sensor-setting="preset"]')).toBeEnabled();
    await prepare.locator('[data-sensor-setting="preset"]').selectOption('wide');
    await expect(prepare.locator('[data-guide-step="reception"]')).toHaveAttribute('data-complete', 'true');
    await expect(prepare.locator('[data-guide-action="next"]')).toBeHidden();
    await expect(prepare.locator('[data-guide-action="measure"]')).toBeEnabled();
    await prepare.locator('[data-guide-action="disconnect"]').click();
    await expect(prepare.locator('[data-guide-action="measure"]')).toBeHidden();
    await prepare.locator('[data-guide-action="connect"]').click();
    await expect(prepare.locator('[data-guide-action="measure"]')).toBeEnabled();
    await expect(prepare.locator('[data-guide-action="next"]')).toBeHidden();
    await page.mouse.move(0, 0);
    await page.screenshot({ path: testInfo.outputPath('settings.png'), fullPage: true });
    await prepare.locator('[data-guide-action="measure"]').click();
    await page.locator('.luminous-settings').click();
    const dialog = page.locator('#measurement-settings');
    await expect(dialog.locator('[data-sensor-setting="preset"]')).toHaveValue('wide');
    await page.mouse.move(0, 0);
    await page.screenshot({ path: testInfo.outputPath('dialog-settings.png'), fullPage: true });
    await dialog.locator('.luminous-close').click();
    await expect(page.locator('#start-recording')).toBeEnabled();
    await page.locator('#start-recording').click();
    await page.locator('#capture-continuous-point').click();
    await page.locator('#finish-recording').click();
    await expect(page.locator('#additional-recording')).toBeEnabled();
    await page.locator('.luminous-settings').click();
    await expect(dialog.locator('[data-sensor-setting="preset"]')).toBeDisabled();
    await page.mouse.move(0, 0);
    await page.screenshot({ path: testInfo.outputPath('locked-settings.png'), fullPage: true });
    await dialog.locator('.luminous-close').click();
    await page.screenshot({ path: testInfo.outputPath('measure.png'), fullPage: true });
    await page.reload();
    await page.locator('.luminous-settings').click();
    await expect(dialog.locator('[data-sensor-setting="preset"]')).toHaveValue('wide');
    await page.locator('#connect').click();
    await dialog.locator('.luminous-close').click();
    await expect(page.locator('#additional-recording')).toBeEnabled();
    await page.locator('.luminous-export > summary').click();
    const pending = page.waitForEvent('download');
    await page.locator('#export-points-csv').click();
    const download = await pending, chunks = [];
    for await (const chunk of await download.createReadStream()) chunks.push(chunk);
    const imported = await page.evaluate(async text => (await import('/src/data/files/csv.js')).parseExperimentCsv(text), Buffer.concat(chunks).toString('utf8'));
    expect(imported.samples).toHaveLength(1);
    expect(imported.run.context.channels.map(c => c.id)).toEqual(['magneticX', 'magneticY', 'magneticZ', 'magneticStrength']);
    const v = imported.samples[0].values;
    expect(Object.keys(v)).toHaveLength(4);
    expect(v.magneticZ).toBe(363);
    expect(v.magneticStrength).toBeCloseTo(Math.hypot(v.magneticX, v.magneticY, v.magneticZ));
    await page.locator('#prepare-new-experiment').click();
    await page.locator('.luminous-settings').click();
    await expect(dialog.locator('[data-sensor-setting="preset"]')).toBeEnabled();
    await expect(dialog.locator('[data-sensor-setting="preset"]')).toHaveValue('wide');
    await dialog.locator('[data-sensor-setting="preset"]').selectOption('normal');
    await dialog.locator('.luminous-close').click();
    await expect(page.locator('#start-recording')).toBeEnabled();
  });
}
