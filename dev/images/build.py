"""Create display-only WebP derivatives. Original illustrations stay unchanged."""
import json
from pathlib import Path
from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parents[2]
sources = sorted({
    *ROOT.glob('public/activities/*/experiment-*.png'),
    *ROOT.glob('public/assets/devices/posters/*.png'),
    ROOT / 'public/assets/design/luminous-usb.png',
    ROOT / 'src/catalog/sensors/magnetometer/calibration.png',
})
manifest = {}
for source in sources:
    with Image.open(source) as original:
        original = ImageOps.exif_transpose(original).convert('RGBA')
        variants = []
        for maximum, suffix in [(1280, ''), (640, '-640')]:
            image = original.copy()
            image.thumbnail((maximum, maximum), Image.Resampling.LANCZOS)
            target = source.with_name(source.stem + suffix + '.webp')
            image.save(target, 'WEBP', quality=88, method=6, exact=True)
            variants.append({'file': target.relative_to(ROOT).as_posix(), 'width': image.width, 'height': image.height})
        manifest[source.relative_to(ROOT).as_posix()] = {
            'file': variants[0]['file'], 'width': variants[0]['width'], 'height': variants[0]['height'],
            'small': variants[1]['file'], 'smallWidth': variants[1]['width'],
        }
        print(f'{source.name}: {source.stat().st_size} -> {source.with_suffix(".webp").stat().st_size} bytes')
(ROOT / 'src/app/guide-image-assets.js').write_text(
    '// Generated by dev/images/build.py; original artwork is retained.\nexport const guideImages = '
    + json.dumps(manifest, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
