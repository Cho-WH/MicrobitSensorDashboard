// Export verified partial and full-application trial images with the pinned HEX reader.
import { writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { readTrialImage } from './trial-image.mjs';
import { createInitPacket, verifyFullImage, appStart, appLimit } from '../bluetooth-install/full-image.js';
const hash = bytes => createHash('sha256').update(bytes).digest('hex');
const output = new URL('../bluetooth-install/firmware/', import.meta.url);
const programs = [], fullPrograms = [], binaries = [];
let commonRuntime;
for (const [id, name] of [['temperature', '온도 시험본 B'], ['light-level', '밝기 시험본 B'],
  ['accelerometer', '가속도 시험본'], ['magnetometer', '자기장 시험본'], ['bmp280', 'BMP280 수정 시험본'],
  ['analog-raw', '아날로그 P0·P1·P2 시험본'], ['temperature-light', '온도·밝기 결합 예제']]) {
  const { map, program, bytes, runtime } = await readTrialImage(id, name);
  if (commonRuntime && !runtime.equals(commonRuntime)) throw new Error('Trial runtimes differ byte-for-byte');
  commonRuntime = runtime;
  programs.push(program);
  binaries.push({ file: program.file, bytes });
  // Full DFU remains a historical two-program experiment, not an expansion path.
  if (!['temperature', 'light-level'].includes(id)) continue;
  let fullEnd = appStart;
  for (const [address, block] of map) if (address < appLimit && address + block.length > appStart)
    fullEnd = Math.max(fullEnd, Math.min(address + block.length, appLimit));
  fullEnd = Math.ceil(fullEnd / 4) * 4;
  const full = map.slicePad(appStart, fullEnd - appStart), init = await createInitPacket(full);
  const fullFile = `${id}-full-v1.bin`, initFile = `${id}-full-v1.dat`;
  const target = { ...programs.at(-1), file: fullFile, initFile, start: appStart, end: fullEnd,
    bytes: full.length, sha256: hash(full), initSha256: hash(init) };
  await verifyFullImage(target, full, init);
  fullPrograms.push(target); binaries.push({ file: fullFile, bytes: full }, { file: initFile, bytes: init });
}
await mkdir(output, { recursive: true });
for (const { file, bytes } of binaries) await writeFile(new URL(file, output), bytes);
await writeFile(new URL('programs.js', output), '// Generated by dev/firmware/export-partial-trials.mjs. Do not edit hashes by hand.\nexport const trialPrograms = Object.freeze(' + JSON.stringify(programs, null, 2) + '.map(Object.freeze));\n');
console.log(programs);
await writeFile(new URL('full-programs.js', output), '// Generated by dev/firmware/export-partial-trials.mjs. Application only; no SoftDevice or bootloader.\nexport const fullPrograms = Object.freeze(' + JSON.stringify(fullPrograms, null, 2) + '.map(Object.freeze));\n');
console.log(fullPrograms);
