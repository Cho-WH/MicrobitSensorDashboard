// Publish the verified common B runtime for the five registered sensors.
// Reuses the HEX inspector: no second compile or independently generated binary.
import { readFile, writeFile, copyFile, mkdir } from 'node:fs/promises';
import { readFirmwareImage } from './firmware-image.mjs';
import { normalizeText, readJson, parseArgs } from './build-support.mjs';
const output = new URL('../../public/firmware/', import.meta.url);
const config = await readJson(new URL('targets.json', import.meta.url));
const releases = parseArgs([], Object.keys(config.targets), config.releases).targets;
const entries = {};
const verified = [];
let shared;
for (const sensor of releases) {
  const { id, version } = config.targets[sensor];
  const { program, bytes, runtime, record, base } = await readFirmwareImage(sensor);
  if (shared && !shared.equals(runtime)) throw new Error('Runtime mismatch: ' + sensor);
  shared = runtime;
  const stem = `${id}-v${version}`;
  const hex = await readFile(new URL(base + '.hex'));
  let previous;
  try { previous = await readFile(new URL(stem + '.hex', output)); } catch (error) { if (error.code !== 'ENOENT') throw error; }
  if (previous && normalizeText(previous) !== normalizeText(hex)) throw new Error('Already published; assign a new version before changing ' + stem);
  const source = await readFile(new URL(base + '.ts'), 'utf8');
  verified.push({ program, bytes, record, id, stem, base, source, version, sensor });
}
// Validate every sensor and the shared native bytes before updating release files.
await mkdir(output, { recursive: true });
for (const { program, bytes, record, id, stem, base, source, version, sensor } of verified) {
  await copyFile(new URL(base + '.hex'), new URL(stem + '.hex', output));
  await writeFile(new URL(stem + '.bin', output), bytes);
  await writeFile(new URL(stem + '.ts', output), source);
  await writeFile(new URL(stem + '.build.json', output), JSON.stringify({ ...record, id, version,
    release: { profile: 'common-runtime-b', build: 'dev/firmware/build.mjs',
      publisher: 'dev/firmware/publish.mjs', partialSha256: program.sha256,
      runtimeSha256: program.runtimeSha256, hardwareScope: 'automated build and protocol checks only; V1 display and device acceptance pending' } }, null, 2) + '\n');
  entries[id] = { id, sensorId: sensor, version, name: config.targets[sensor].displayName,
    boards: ['micro:bit-v2'], digestMode: 'utf8-crlf-to-lf', ...record.protocol, hardwareVerified: false,
    fileName: stem + '.hex', sha256: program.hexSha256,
    partial: { ...program, file: stem + '.bin' } };
  // Build records hold provenance; do not repeat full records in the browser manifest.
  entries[id].source = { path: record.source, build: 'dev/firmware/publish.mjs',
    buildRecord: 'public/firmware/' + stem + '.build.json', target: record.target, compiler: record.compiler };
}
await writeFile(new URL('../../src/device/wireless-firmware.js', import.meta.url),
  '// Generated by dev/firmware/publish.mjs.\nexport const wirelessFirmware = ' + JSON.stringify(entries, null, 2) + ';\n');
console.log('Published verified USB/partial pairs: ' + Object.keys(entries).join(', '));
