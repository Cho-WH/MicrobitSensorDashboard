import { readFile, writeFile } from 'node:fs/promises';

// Independent shape candidate. Read the archived primary for its palette;
// never regenerate or overwrite any of the four existing variants here.
const root = new URL('./', import.meta.url);
const n = value => Number(value.toFixed(3));
const point = (radius, angle) => {
  const radians = angle * Math.PI / 180;
  return [n(64 + radius * Math.cos(radians)), n(63.5 + radius * Math.sin(radians))];
};
const p = (radius, angle) => point(radius, angle).join(' ');

// Keep the primary's frame untouched and retain its internal line weights.
// Only the track openings change: continuous lower half, larger right opening.
function band(start, end, width, rounding) {
  const outer = 28 + width / 2, inner = 28 - width / 2;
  const outerInset = Math.asin(rounding / outer) * 180 / Math.PI;
  const innerInset = Math.asin(rounding / inner) * 180 / Math.PI;
  const large = end - start > 180 ? 1 : 0;
  return `M${p(outer,start+outerInset)}A${outer} ${outer} 0 ${large} 1 ${p(outer,end-outerInset)}Q${p(outer,end)} ${p(outer-rounding,end)}L${p(inner+rounding,end)}Q${p(inner,end)} ${p(inner,end-innerInset)}A${inner} ${inner} 0 ${large} 0 ${p(inner,start+innerInset)}Q${p(inner,start)} ${p(inner+rounding,start)}L${p(outer-rounding,start)}Q${p(outer,start)} ${p(outer,start+outerInset)}Z`;
}

let svg = await readFile(new URL('archive/sensor-lab-primary.svg',root),'utf8');
function replace(pattern, replacement) {
  if (!pattern.test(svg)) throw new Error(`Primary structure changed: ${pattern}`);
  svg = svg.replace(pattern,replacement);
}
replace(/<title id="title">.*?<\/title>/, '<title id="title">센서 실험실 — 열린 궤도와 빛나는 신호점</title>');
replace(/<desc id="desc">.*?<\/desc>/, '<desc id="desc">기존 기본형의 선 두께를 유지한 별도 형태 시안. 아래쪽 궤도는 이어지고 오른쪽은 넓게 열린다. 오른쪽 눈금은 바깥 끝을 소폭 줄였다. 호는 시작부터 선명한 주황색이며 노란 하이라이트가 있는 신호점으로 밝아진다.</desc>');
replace(/<!-- Generated by build-icons\.mjs\..*?-->/, '<!-- Generated by build-shape-study.mjs; existing primary remains unchanged. -->');
replace(/<g id="orbit-ring">[\s\S]*?<\/g>/, `<g id="orbit-ring">
    <path id="orbit-open" d="${band(42,264,3.2,.18)}" fill="#244a91"/>
    <path id="orbit-signal" d="${band(290,334.5,3.1,.45)}" fill="url(#upper-signal-paint)"/>
  </g>`);
replace(/<path id="orbit-bright-left"[^>]*\/>/, `<path id="orbit-bright-left" d="${band(95.3,210.5,3.6,.55)}" fill="url(#bright-left-paint)"/>`);
const [signalX,signalY] = point(28,334.5);
const [startX,startY] = point(28,290);
replace(/<linearGradient id="upper-signal-paint"[\s\S]*?<\/linearGradient>/, `<linearGradient id="upper-signal-paint" x1="${startX}" y1="${startY}" x2="${signalX}" y2="${signalY}" gradientUnits="userSpaceOnUse">
      <stop stop-color="#ff934f"/><stop offset=".55" stop-color="#ffb45f"/><stop offset="1" stop-color="#ffd36b"/>
    </linearGradient>`);
// Shorten only the outside end, preserving the spacing around the subject.
replace(/d="M82\.5 63\.5H100\.5"/, 'd="M82.5 63.5H98"');
replace(/(<linearGradient id="right-tick"[^>]*x2=")100\.5(")/, '$198$2');
replace(/<radialGradient id="signal-glow"[\s\S]*?<\/radialGradient>/, `<radialGradient id="signal-glow" cx="${signalX}" cy="${signalY}" r="9.5" gradientUnits="userSpaceOnUse">
      <stop stop-color="#ffd36b" stop-opacity=".52"/><stop offset=".28" stop-color="#ffb344" stop-opacity=".32"/><stop offset=".6" stop-color="#ff7a45" stop-opacity=".11"/><stop offset="1" stop-color="#ff7a45" stop-opacity="0"/>
    </radialGradient>`);
replace(/<linearGradient id="signal-paint"[\s\S]*?<\/linearGradient>/, `<radialGradient id="signal-paint" cx="${n(signalX-.85)}" cy="${n(signalY-1.15)}" r="4.8" gradientUnits="userSpaceOnUse">
      <stop stop-color="#fff4b8"/><stop offset=".22" stop-color="#ffe078"/><stop offset=".56" stop-color="#ffb344"/><stop offset="1" stop-color="#ff7a45"/>
    </radialGradient>`);
replace(/<circle id="signal-aura"[^>]*\/>/, `<circle id="signal-aura" cx="${signalX}" cy="${signalY}" r="9.5" fill="url(#signal-glow)"/>`);
replace(/<circle id="signal-point"[^>]*\/>/, `<circle id="signal-point" cx="${signalX}" cy="${signalY}" r="3.25" fill="url(#signal-paint)"/>`);
// This candidate has no lower warm segment.
replace(/    <linearGradient id="lower-signal-paint"[\s\S]*?<\/linearGradient>\r?\n/, '');
await writeFile(new URL('sensor-lab-open-orbit.svg',root),svg);
console.log('Created independent open-orbit candidate; existing SVGs were not written.');
